// Operator-run public metadata summary. Never opens raw/session/auth inputs.
import { readFile, writeFile, rename, lstat } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { readSelected, verifyEvidenceBytes } from './verify-evidence.js';
import { SESSION_ID } from './export-codex-evidence.js';
export function evidenceSessionMarkdown(summary, manifest) {
  if (
    summary.sessionID !== SESSION_ID ||
    summary.exportSHA256 !== manifest.exportSHA256 ||
    summary.cutoff !== manifest.cutoff ||
    summary.sourceRunLogCount !== manifest.sourceRunLogs.length ||
    manifest.secondaryScan?.status !== 'zero-findings'
  )
    throw Error('Verified metadata required');
  return `# Original authoring session and evidence

<!-- Generated by scripts/update-evidence-summary.js after evidence verification. -->

${manifest.formatVersion === 2 ? `**${SESSION_ID}** is the original primary author and integration lead represented by this original-session fixed snapshot, not the sole author of the current repository. Other owner-authorized coding, documentation and QA sessions are registered in [CODEX_SESSIONS](docs/CODEX_SESSIONS.md); their transcripts are not included in this original-only selected export. Lead-owned history integration is separate from evidence coverage; original-only export coverage does not establish complete code authorship. Operators own native QA, Git and cloud actions. Main follows the actually deployed source, not unpromoted work.` : `**${SESSION_ID}** is the sole Codex source/docs session. Resume it; do not fork, delegate or substitute another author. Operators own native QA, Git and cloud actions. Main follows the actually deployed source, not unpromoted work.`}

## Current verified selected export

| Metadata | Value |
|---|---|
| Cutoff | ${summary.cutoff} |
| Selected entries | ${summary.exportedEntries} |
| CLI-log digests | ${summary.sourceRunLogCount} (${manifest.sourceRunLogs[0].leaf}–${manifest.sourceRunLogs.at(-1).leaf}) |
| Selected bytes | ${manifest.exportBytes} |${manifest.formatVersion === 2 ? `\n| Ordered transcript components | ${manifest.parts.length}; entry-aligned, each ≤16 MiB; index is not the transcript |` : ''}
| Selected SHA256 | \`${summary.exportSHA256}\` |
| Secondary whole-entry omissions | ${summary.secondaryOmittedEntries} |
| Secondary rescan | zero-findings, bound to this exact selected SHA |

These are fixed-snapshot metadata, not a claim that later runs or this generation command are already included. Refresh after the writer stops, sanitize every finding, rescan to zero, then regenerate this file. The manifest is authoritative; CI checks this summary against it.

Raw snapshots stay private/ignored and are never linked or force-added. Private reasoning, system/developer/bootstrap instructions, opaque fields, media and unselected metadata are omitted. Strong key detection remains fatal. The readable selected export is **not raw-complete evidence**. CLI-log digests are metadata, not published reasoning. The source author did not read raw or selected transcript content.

[Built with Codex timeline](BUILT_WITH_CODEX.md) · [evidence procedure](docs/CODEX_EVIDENCE.md) · [historical delivery notes](docs/ops/DELIVERY_HISTORY.md).
`;
}
export async function updateEvidenceSummary({ root = process.cwd(), check = false } = {}) {
  const { bytes, manifest } = await readSelected(root);
  const summary = verifyEvidenceBytes(bytes, manifest);
  const markdown = evidenceSessionMarkdown(summary, manifest);
  const output = join(root, 'CODEX_SESSION.md');
  const info = await lstat(output);
  if (!info.isFile() || info.isSymbolicLink() || info.nlink !== 1 || info.size > 1024 * 1024)
    throw Error('Summary destination rejected');
  const current = await readFile(output, 'utf8');
  if (check) {
    if (current !== markdown) throw Error('Evidence summary is stale');
  } else if (current !== markdown) {
    const temporary = output + '.summary.tmp';
    await writeFile(temporary, markdown, { flag: 'wx', mode: 0o644 });
    await rename(temporary, output);
  }
  return {
    cutoff: summary.cutoff,
    sourceRunLogCount: summary.sourceRunLogCount,
    matches: check || current === markdown,
  };
}
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    if (process.argv.length > 3 || (process.argv.length === 3 && process.argv[2] !== '--check'))
      throw Error('Arguments rejected');
    console.log(
      JSON.stringify(await updateEvidenceSummary({ check: process.argv[2] === '--check' })),
    );
  } catch {
    console.error(
      'Verified evidence summary failed closed; regenerate only after a zero-finding rescan.',
    );
    process.exitCode = 1;
  }
}
